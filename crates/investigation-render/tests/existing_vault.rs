    // A nested prefix whose parent is missing: refused, nothing created.
    let workspace = configure(&root, &existing(&fixture.vault, "Projects/Investigation")).unwrap();
    fixture.store = Store::open(workspace);
    let before = fingerprint(&fixture.vault, "-");
