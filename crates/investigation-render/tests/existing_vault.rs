const PREFIX: &str = "Investigation";
const FOREIGN: &str = "FOREIGN-MARKER";

fn submit(store: &mut Store, key: &str, case_id: Option<Id>, operation: Value) -> Id {
    let input = json!({
        "schema_version":"inv.command.v0-alpha",
        "command_id":key,
        "case_id":case_id,
        "actor":"agent:existing-vault-test",
        "preconditions":[],
        "operations":[operation]
    });
    let receipt = store.record(&serde_json::to_vec(&input).unwrap()).unwrap();
    receipt.created[0].id
}

fn question(store: &mut Store, wording: &str, case_id: Id) -> Id {
    submit(
        store,
        wording,
        Some(case_id),
        json!({"op":"question.create", "payload":{"wording":wording, "importance":"normal"}}),
    )
}

/// Rewrite the workspace's vault policy and reopen it.
fn configure(
    root: &Path,
    lines: &str,
) -> Result<Workspace, investigation_store::workspace::WorkspaceError> {
    let config = root.join("investigation.toml");
    let original = fs::read_to_string(&config).unwrap();
    let original = original
        .lines()
        .filter(|line| {
            !line.starts_with("existing_vault")
                && !line.starts_with("managed_prefix")
                && !line.starts_with("viewer_release")
        })
        .collect::<Vec<_>>()
        .join("\n")
        + "\n";
    let updated = original.replace(
        "preserve_human_folders = true\n",
        &format!("preserve_human_folders = true\n{lines}"),
    );
    assert_ne!(original, updated);
    fs::write(&config, updated).unwrap();
    Workspace::open(root)
}

fn existing(vault: &Path, prefix: &str) -> String {
    format!(
        "viewer_release = \"1.15.1\"\nexisting_vault = {:?}\nmanaged_prefix = {prefix:?}\n",
        vault.to_str().unwrap()
    )
}

