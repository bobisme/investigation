/// The property-type table in `obsidian/README.md` lists every `inv_`
/// property a rendered note carries, with the type its value has.
#[test]
fn the_documented_property_types_match_the_rendered_frontmatter() {
    let readme = include_str!("../../../obsidian/README.md");
    let table = &readme[readme.find("### Property types").unwrap()..];
    let mut documented = BTreeMap::new();
    for row in table.lines().filter(|line| line.starts_with("| ")) {
        let cells: Vec<&str> = row.split(" | ").collect();
        if cells.len() < 2 || cells[0] == "| Type" {
            continue;
        }
        for name in cells[1].trim_end_matches(" |").split(", ") {
            documented.insert(name.trim_matches('`').to_owned(), cells[0][2..].to_owned());
        }
    }
    let mut fixture = Fixture::new();
    fixture.render().unwrap();
    let mut seen = 0;
    for (path, bytes) in files(&fixture.prefix()) {
        let text = String::from_utf8(bytes).unwrap();
        let Some(front) = text
            .strip_prefix("---\n")
            .and_then(|rest| rest.split_once("\n---\n"))
            .map(|(front, _)| front)
        else {
            continue;
        };
        for line in front.lines() {
            let Some((key, value)) = line.split_once(':') else {
                continue;
            };
            if !key.starts_with("inv_") {
                continue;
            }
            let value = value.trim();
            let kind = if value == "true" || value == "false" {
                "Checkbox"
            } else if !value.is_empty() && value.bytes().all(|b| b.is_ascii_digit()) {
                "Number"
            } else if value.starts_with("\"[[") {
                "Text holding one link"
            } else if value.len() > 10 && value.as_bytes()[4] == b'-' && value.ends_with('Z') {
                "Date & time"
            } else {
                "Text"
            };
            assert_eq!(
                documented.get(key).map(String::as_str),
                Some(kind),
                "{path}: {key} is {kind}"
            );
            seen += 1;
        }
    }
    assert!(seen > 50, "{seen}");
}
