//! Existing-vault mode (W12.06): the casebook renders into one managed
//! prefix folder of a vault a person already has, and nothing else.
//!
//! - `nothing_outside_the_prefix_changes_through_render_reconcile_and_removal`:
//!   a vault full of unrelated notes, dotfiles, a viewer configuration
//!   folder with settings, themes and plugins, and notes at the very paths
//!   the renderer generates (`Start Here.md`, `Cases/<case>/Overview.md`)
//!   is fingerprinted (every byte, type, mode, link target and file mtime
//!   outside the prefix); it is unchanged after a render, a drifted render,
//!   `preserve-as-note`, `release-path`, a re-render after a new record,
//!   a `vault copy-map` (whose board lands in the prefix's `Boards/`, with
//!   file nodes that carry the prefix and resolve, beside a foreign
//!   `Boards/` folder it never touches), and the removal of the projection. The manifest lists every file the
//!   renderer wrote inside the prefix, and the removal deletes only owned
//!   files with their generated bytes.
//! - `generated_views_never_show_foreign_notes_and_links_stay_inside_the_prefix`:
//!   every wikilink and Canvas file path resolves to a generated file inside
//!   the prefix, every Base filters on the exact case ID, and the vault's
//!   generated bytes are exactly the pure plan, so no foreign note (even one
//!   titled like a generated note) can appear in a view.
//! - First render, prefix parents, links and a moved setting refuse without
//!   changing anything.

