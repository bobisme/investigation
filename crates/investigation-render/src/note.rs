//! The shared entity-note skeleton. Pure.
//!
//! Every record note has the same frame, in this order:
//!
//! 1. flat `inv_` frontmatter ([`crate::yaml`]);
//! 2. an H1 display title, never an identity;
//! 3. the tool-owned projection banner;
//! 4. a basis table: ID, kind, case, exact revision and snapshot;
//! 5. `## Summary`: short claim, applicability, effective state and caveats;
//! 6. `## Typed links`: what the record relies on and what cites it, each
//!    with the body field that holds the reference;
//! 7. `## Evidence selectors`: exact digest and selector, each with a stable
//!    block anchor derived from them;
//! 8. `## Next action or blocker`: open gaps and freshness blockers.
//!
//! Per-type templates add their own sections on top of this frame. Files and
//! links are named from validated IDs only, so a title change never renames a
//! file or breaks a link. Withheld records keep the frame with ID-only
//! content; their titles, summaries, metadata and lineage never appear.

