/// Frontmatter schema of generated notes.
pub const VAULT_SCHEMA: &str = "inv.vault.v1";

/// Display titles are bounded so headings, aliases and labels stay one line.
pub const TITLE_CHARS: usize = 120;
/// Bound for the short claim and applicability lines.
pub const SUMMARY_CHARS: usize = 600;

/// Marks every generated file as a tool-owned projection.
pub const BANNER: &str = "> [!warning] Tool-owned projection\n\
> Generated by Investigation from a verified snapshot. This file is a tool-owned projection. \
Editing or deleting it is drift: the edited file is left in place but no longer updated, and \
the edit is not recorded.\n\
> Write your own analysis in `Notes/` (or `Boards/`, `Inbox/`), and record changes through \
Investigation operations.\n";

/// Body fields that carry a record's display title, in preference order.
fn title_fields(kind: Kind) -> &'static [&'static str] {
    match kind {
        Kind::Case => &["title"],
        Kind::Question => &["wording", "title"],
        Kind::Source => &["title", "identity", "publisher", "locator"],
        Kind::Artifact => &["derivation.label", "title", "name", "format", "media_type"],
        Kind::Observation => &[
            "value.statement",
            "value.description",
            "basis.assertion",
            "claim",
            "statement",
        ],
        Kind::Hypothesis => &["statement", "title", "description"],
        Kind::Assumption => &["claim", "statement", "title", "description"],
        Kind::Option | Kind::Criterion => &["title", "name", "description"],
        Kind::Comparison => &["title", "summary", "reason"],
        Kind::Assessment => &["title", "summary", "reason", "rationale"],
        Kind::Conclusion | Kind::Objection => &["statement", "claim", "challenge", "title"],
        Kind::Decision => &["title", "statement", "choice.reason", "content.statement"],
        Kind::Review => &["title", "scope", "summary", "method"],
        Kind::Annotation => &["content.text", "text", "title"],
        Kind::Retrospective => &["title", "summary", "lesson"],
        Kind::Inquiry => &["title", "question", "description", "purpose"],
        Kind::Run => &["title", "operation", "intent.intent"],
        _ => &["title", "name"],
    }
}

/// Body fields that state where a claim applies.
const APPLICABILITY_FIELDS: &[&str] = &["applicability", "scope", "scope_statement"];

pub(crate) fn value_at<'a>(body: &'a Value, dotted: &str) -> Option<&'a Value> {
    dotted
        .split('.')
        .try_fold(body, |value, key| value.get(key))
}

/// A string field, or the value of an explicitly known `Knowledge` string.
pub(crate) fn text_at<'a>(body: &'a Value, dotted: &str) -> Option<&'a str> {
    let value = value_at(body, dotted)?;
    value.as_str().or_else(|| {
        (value.get("state").and_then(Value::as_str) == Some("known"))
            .then(|| value.get("value").and_then(Value::as_str))
            .flatten()
    })
}

fn first_text<'a>(body: &'a Value, fields: &[&str]) -> Option<&'a str> {
    fields
        .iter()
        .filter_map(|field| text_at(body, field))
        .find(|text| !text.trim().is_empty())
}

/// The snake_case wire word of a unit-like enum or a `kind`- or
/// `type`-tagged one.
pub(crate) fn wire_word(value: &impl Serialize) -> String {
    match serde_json::to_value(value) {
        Ok(Value::String(word)) => word,
        Ok(Value::Object(map)) => map
            .get("kind")
            .or_else(|| map.get("type"))
            .and_then(Value::as_str)
            .unwrap_or("unknown")
            .to_owned(),
        _ => "unknown".to_owned(),
    }
}

pub(crate) const fn level_word(level: ClassificationLevel) -> &'static str {
    match level {
        ClassificationLevel::Public => "public",
        ClassificationLevel::Internal => "internal",
        ClassificationLevel::Restricted => "restricted",
    }
}

/// One record body citing another record's exact revision.
#[derive(Debug, Clone)]
pub(crate) struct Citation {
    pub by: Id,
    pub field: &'static str,
    pub cites: RevisionRef,
}

/// A reference in a record body that is not a dependency edge: a rival, a
/// superseding record, a step's support, an acceptance record. It links both
/// ways like an edge but carries no freshness. Bare IDs have no revision.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct Mention {
    pub by: Id,
    /// Dotted body path without list indices.
    pub field: String,
    pub target: Id,
    pub revision: Option<u64>,
}

/// Every reference in `record`'s body that no dependency edge already covers,
/// in body order, once per field and target: exact `{id, revision}` objects
/// anywhere, and bare IDs in fields named `*_ref` or `*_refs`.
pub(crate) fn mentions(record: &Record) -> Vec<Mention> {
    fn walk(value: &Value, path: &mut Vec<String>, found: &mut Vec<(String, Id, Option<u64>)>) {
        let referencing = path
            .last()
            .is_some_and(|key| key.ends_with("_ref") || key.ends_with("_refs"));
        match value {
            Value::Object(map) => {
                if let (Some(id), Some(revision)) = (
                    map.get("id")
                        .and_then(Value::as_str)
                        .and_then(|id| id.parse::<Id>().ok()),
                    map.get("revision").and_then(Value::as_u64),
                ) {
                    found.push((path.join("."), id, Some(revision)));
                    return;
                }
                for (key, child) in map {
                    path.push(key.clone());
                    walk(child, path, found);
                    path.pop();
                }
            }
            Value::Array(items) => {
                for item in items {
                    walk(item, path, found);
                }
            }
            Value::String(text) if referencing => {
                if let Ok(id) = text.parse::<Id>() {
                    found.push((path.join("."), id, None));
                }
            }
            _ => {}
        }
    }
    let edges: Vec<Id> = dependency_edges(record)
        .unwrap_or_default()
        .into_iter()
        .map(|edge| edge.target.id)
        .collect();
    let mut found = Vec::new();
    walk(&record.body, &mut Vec::new(), &mut found);
    let mut out: Vec<Mention> = Vec::new();
    for (field, target, revision) in found {
        if target == record.header.id || edges.contains(&target) {
            continue;
        }
        let mention = Mention {
            by: record.header.id,
            field,
            target,
            revision,
        };
        if !out.contains(&mention) {
            out.push(mention);
        }
    }
    out
}

/// Everything a note needs about its case, computed once per case and plan.
pub struct NoteContext<'a> {
    case: &'a CaseSnapshot,
    policy: &'a ViewPolicy,
    generation: &'a Generation,
    audience: AudiencePolicy,
    classifier: Classifier<'a>,
    freshness: FreshnessIndex,
    cited_by: BTreeMap<Id, Vec<Citation>>,
    mentioned_by: BTreeMap<Id, Vec<Mention>>,
    /// Open gaps by subject ID, or `None` when the inventory failed.
    gaps: Option<BTreeMap<Id, Vec<Gap>>>,
    /// Gaps whose reason was computed from a record the audience may not
    /// see. Their reasons can quote its fields, so only the rule is named.
    withheld_gaps: BTreeSet<String>,
    /// Reviews and objections of this case by kind and the `subject_ref.id`
    /// text they name, each list in record order.
    by_subject: BTreeMap<Kind, BTreeMap<&'a str, Vec<&'a Record>>>,
    /// Hypotheses by the `question_ref.id` text they name, in record order.
    hypotheses_by_question: BTreeMap<&'a str, Vec<&'a Record>>,
    /// The consequences table of every question of this case with an active
    /// criterion, judged against [`Self::freshness`] and built on first use.
    tables: OnceCell<BTreeMap<Id, ConsequencesTable>>,
}

impl<'a> NoteContext<'a> {
    pub fn new(case: &'a CaseSnapshot, policy: &'a ViewPolicy, generation: &'a Generation) -> Self {
        let state = case.state();
        let mut cited_by: BTreeMap<Id, Vec<Citation>> = BTreeMap::new();
        let mut mentioned_by: BTreeMap<Id, Vec<Mention>> = BTreeMap::new();
        let mut by_subject: BTreeMap<Kind, BTreeMap<&'a str, Vec<&'a Record>>> = BTreeMap::new();
        let mut hypotheses_by_question: BTreeMap<&'a str, Vec<&'a Record>> = BTreeMap::new();
        for record in state.records() {
            let kind = record.header.id.kind();
            if matches!(kind, Kind::Review | Kind::Objection)
                && record.header.case_id == case.case_id()
                && let Some(subject) = text_at(&record.body, "subject_ref.id")
            {
                by_subject
                    .entry(kind)
                    .or_default()
                    .entry(subject)
                    .or_default()
                    .push(record);
            }
            if kind == Kind::Hypothesis
                && let Some(question) = text_at(&record.body, "question_ref.id")
            {
                hypotheses_by_question
                    .entry(question)
                    .or_default()
                    .push(record);
            }
            for mention in mentions(record) {
                mentioned_by
                    .entry(mention.target)
                    .or_default()
                    .push(mention);
            }
            // Unreadable references surface as a freshness caveat on the record.
            for edge in dependency_edges(record).unwrap_or_default() {
                cited_by.entry(edge.target.id).or_default().push(Citation {
                    by: record.header.id,
                    field: edge.field,
                    cites: edge.target,
                });
            }
        }
        let audience = policy.audience_policy();
        let classifier = Classifier::new(state);
        let mut withheld_gaps = BTreeSet::new();
        let gaps = enumerate_gaps(state, case.head(), case.case_id())
            .ok()
            .map(|inventory| {
                let mut by_subject: BTreeMap<Id, Vec<Gap>> = BTreeMap::new();
                for gap in inventory.gaps {
                    let read = gap
                        .subject_refs
                        .iter()
                        .chain(&gap.read_set)
                        .chain(gap.prerequisites.iter().flat_map(|p| &p.subject_refs));
                    if !reads_only_visible(&classifier, &audience, read) {
                        withheld_gaps.insert(gap.gap_id.clone());
                    }
                    if gap.status == GapStatus::Resolved {
                        continue;
                    }
                    for subject in &gap.subject_refs {
                        by_subject.entry(subject.id).or_default().push(gap.clone());
                    }
                }
                by_subject
            });
        Self {
            case,
            policy,
            generation,
            audience,
            classifier,
            freshness: FreshnessIndex::build(state, case.case_id()),
            cited_by,
            mentioned_by,
            gaps,
            withheld_gaps,
            by_subject,
            hypotheses_by_question,
            tables: OnceCell::new(),
        }
    }

    /// Reviews (or objections, by `kind`) of this case whose `subject_ref.id`
    /// is `id`, in record order, before any view-policy filtering.
    pub(crate) fn naming_subject(&self, kind: Kind, id: Id) -> &[&'a Record] {
        self.by_subject
            .get(&kind)
            .and_then(|by_id| by_id.get(id.to_string().as_str()))
            .map_or(&[], Vec::as_slice)
    }

    /// Hypotheses whose `question_ref.id` is `question`, in record order.
    pub(crate) fn hypotheses_of(&self, question: &str) -> &[&'a Record] {
        self.hypotheses_by_question
            .get(question)
            .map_or(&[], Vec::as_slice)
    }

    /// The consequences table of `question` at this snapshot, or `None` when
    /// it has no active criterion, is not in this case or its table cannot be
    /// computed. A table with no criterion is never shown, so leaving those
    /// out changes no note. Every question's table is built on the first call,
    /// in one pass over the case and against its one freshness index.
    pub(crate) fn consequences_table(&self, question: Id) -> Option<&ConsequencesTable> {
        self.tables
            .get_or_init(|| {
                let state = self.case.state();
                weighting::consequences_tables_with(state, &self.freshness, self.case.case_id())
                    .map(|tables| {
                        tables
                            .into_iter()
                            .filter_map(|(id, table)| Some((id, table.ok()?)))
                            .collect()
                    })
                    .unwrap_or_default()
            })
            .get(&question)
    }

    /// Whether a gap's (or a `next` step's) reason must not be shown because
    /// it was computed from a record the audience may not see.
    pub(crate) fn gap_withheld(&self, gap_id: &str) -> bool {
        self.withheld_gaps.contains(gap_id)
    }

    /// Unresolved gaps with `id` among their subjects, in inventory order,
    /// or `None` when the gap inventory is unavailable at this snapshot.
    pub(crate) fn open_gaps(&self, id: Id) -> Option<&[Gap]> {
        self.gaps
            .as_ref()
            .map(|gaps| gaps.get(&id).map_or(&[][..], Vec::as_slice))
    }

    /// How many distinct unresolved gaps name `id`, or `None` when the gap
    /// inventory is unavailable: the `inv_open_gaps` property.
    pub(crate) fn open_gap_count(&self, id: Id) -> Option<usize> {
        self.open_gaps(id).map(|gaps| {
            gaps.iter()
                .map(|gap| gap.gap_id.as_str())
                .collect::<BTreeSet<_>>()
                .len()
        })
    }

    pub const fn case(&self) -> &'a CaseSnapshot {
        self.case
    }

    pub const fn policy(&self) -> &'a ViewPolicy {
        self.policy
    }

    pub const fn generation(&self) -> &'a Generation {
        self.generation
    }

    /// The freshness index of this case at this snapshot.
    pub(crate) const fn freshness(&self) -> &FreshnessIndex {
        &self.freshness
    }

    /// Dependency edges of other records that cite `id`, in record order.
    pub(crate) fn citations(&self, id: Id) -> &[Citation] {
        self.cited_by.get(&id).map_or(&[], Vec::as_slice)
    }

    /// References to `id` that are not dependency edges, in record order.
    pub(crate) fn mentioned_by(&self, id: Id) -> &[Mention] {
        self.mentioned_by.get(&id).map_or(&[], Vec::as_slice)
    }

    /// The classifier every channel decision of this case goes through.
    pub(crate) const fn classifier(&self) -> &Classifier<'a> {
        &self.classifier
    }

    /// Whether this record's title, summary, content and metadata may appear.
    pub fn visible(&self, record: &Record) -> bool {
        self.classifier
            .may_show(record, Field::Summary, &self.audience)
    }

    /// Whether one channel of this record may appear.
    pub(crate) fn may_show(&self, record: &Record, field: Field) -> bool {
        self.classifier.may_show(record, field, &self.audience)
    }

    /// Whether this record is withheld but may still appear as an ID-only
    /// placeholder. Challenges to a visible record (objections, reviews and
    /// assessments of it) are listed this way: its standing is computed on
    /// the full snapshot, so hiding them outright would make it read
    /// stronger than it is. A policy without placeholders omits them.
    pub(crate) fn placeholder(&self, record: &Record) -> bool {
        !self.visible(record) && self.may_show(record, Field::Identity)
    }

    /// Safe display title, or `None` when withheld or nothing displayable.
    pub fn title(&self, record: &Record) -> Option<String> {
        if !self.may_show(record, Field::Title) {
            return None;
        }
        first_text(&record.body, title_fields(record.header.id.kind()))
            .and_then(|text| display_text(text, TITLE_CHARS))
            .or_else(|| self.derived_title(record))
    }

    /// A title composed from typed fields for kinds whose bodies have no
    /// title text: a comparison names its option and criterion, a decision
    /// its choice, a measurement its value. Other records contribute only
    /// their own displayable titles.
    fn derived_title(&self, record: &Record) -> Option<String> {
        let body = &record.body;
        let other = |path: &str| -> Option<String> {
            let id = text_at(body, path)?.parse::<Id>().ok()?;
            let target = self.case.state().current(id)?;
            if target.header.id.kind() == record.header.id.kind() {
                return None;
            }
            self.title(target)
        };
        let title = match record.header.id.kind() {
            Kind::Comparison => format!(
                "{} against {}",
                other("option_ref.id")?,
                other("criterion_ref.id")?
            ),
            // A label, never an imperative sentence around authored text.
            Kind::Decision => format!("Chosen option: {}", other("choice.option_ref.id")?),
            Kind::Observation if text_at(body, "value.kind") == Some("measurement") => {
                let value = text_at(body, "value.value")?;
                match text_at(body, "value.unit") {
                    Some(unit) => format!("Measured {value} {unit}"),
                    None => format!("Measured {value}"),
                }
            }
            Kind::Retrospective => format!(
                "Retrospective at sequence {}",
                body["snapshot"]["sequence"].as_u64()?
            ),
            _ => return None,
        };
        display_text(&title, TITLE_CHARS)
    }

    /// Note path for a record ID: the case Overview for a case, the record's
    /// own note otherwise, or `None` for kinds without a note.
    pub fn note_path(&self, id: Id) -> Result<Option<PlanPath>, RenderError> {
        if id.kind() == Kind::Case {
            return layout::case_overview(id).map(Some);
        }
        layout::record_note(self.case.case_id(), id)
    }

    /// A link to a record by ID with its safe title as display text. Withheld
    /// records show their ID only; records without a note show an inert ID.
    pub fn link(&self, id: Id) -> Result<String, RenderError> {
        let Some(record) = self.case.state().current(id) else {
            return Ok(format!(
                "{} (absent from this snapshot)",
                inline_code(&id.to_string())
            ));
        };
        let display = self.title(record).unwrap_or_else(|| id.to_string());
        Ok(match self.note_path(id)? {
            Some(path) => layout::wikilink(&path, &display),
            None => inline_code(&id.to_string()),
        })
    }

    /// Like [`Self::link`], for a Markdown table cell.
    pub(crate) fn table_link(&self, id: Id) -> Result<String, RenderError> {
        Ok(self.link(id)?.replace('|', "\\|"))
    }

    pub(crate) fn effective(&self, record: &Record) -> Option<&RecordFreshness> {
        self.freshness.get(record.header.id)
    }

    /// Flat frontmatter for a record note or a case Overview.
    pub fn frontmatter(&self, record: &Record) -> Result<String, RenderError> {
        let header = &record.header;
        let kind = layout::kind_name(header.id.kind());
        let head = self.case.head();
        let visible = self.visible(record);
        let mut front = Frontmatter::new();
        front
            .text("inv_id", &header.id.to_string())
            .text("inv_kind", kind)
            .text("inv_case_id", &self.case.case_id().to_string())
            .link("inv_case", &layout::case_overview(self.case.case_id())?);
        if visible {
            let effective = self.effective(record);
            // The lifecycle word comes from the record body: show it as a label.
            let status = effective
                .and_then(|effective| effective.lifecycle.as_deref())
                .and_then(|lifecycle| display_text(lifecycle, TITLE_CHARS))
                .unwrap_or_else(|| "recorded".to_owned());
            front.text("inv_status", &status).text(
                "inv_effective",
                effective.map_or("unknown", |effective| effective.freshness.as_str()),
            );
            crate::evidence::properties(self, record, &mut front);
            crate::records::properties(self, record, &mut front);
        }
        crate::records::listing_properties(self, record, &mut front);
        front
            .integer("inv_revision", header.revision.0)
            // The generation marker (see `crate::marker`): the case head,
            // never the workspace generation, so other cases never churn.
            .integer(marker::SEQUENCE_KEY, head.sequence)
            .text(marker::SNAPSHOT_KEY, head.head_hash.as_str())
            .text("inv_schema", VAULT_SCHEMA);
        if visible {
            front.timestamp("inv_updated", &header.recorded_at);
        } else {
            front.boolean("inv_withheld", true);
        }
        let aliases: Vec<String> = self.title(record).into_iter().collect();
        front
            .list("aliases", &aliases)
            .list("tags", &[format!("investigation/{kind}")]);
        Ok(front.finish())
    }

    /// Frontmatter, H1, banner and basis table: the start of every record
    /// note and case Overview.
    pub fn open_note(&self, out: &mut String, record: &Record) -> Result<(), RenderError> {
        out.push_str(&self.frontmatter(record)?);
        let id = record.header.id.to_string();
        let title = self.title(record).unwrap_or_else(|| id.clone());
        let _ = write!(out, "# {title}\n\n{BANNER}\n");
        self.basis_table(out, record)?;
        if !self.visible(record) {
            let _ = writeln!(
                out,
                "\nContent withheld by the view policy for the `{}` audience.",
                self.policy.audience.as_str()
            );
        }
        Ok(())
    }

    fn basis_table(&self, out: &mut String, record: &Record) -> Result<(), RenderError> {
        let header = &record.header;
        let head = self.case.head();
        let kind = header.id.kind();
        let label = layout::record_kind(kind).map_or(layout::kind_name(kind), |(_, name)| name);
        out.push_str("| Basis | Value |\n|---|---|\n");
        let _ = writeln!(out, "| ID | {} |", table_code(&header.id.to_string()));
        let _ = writeln!(out, "| Kind | {label} |");
        if kind != Kind::Case {
            let _ = writeln!(out, "| Case | {} |", self.table_link(self.case.case_id())?);
        }
        let _ = write!(out, "| Revision | {}", header.revision.0);
        if !header.history.is_empty() {
            let earlier: Vec<String> = header
                .history
                .iter()
                .map(|revision| revision.0.to_string())
                .collect();
            let _ = write!(out, " (earlier: {})", earlier.join(", "));
        }
        out.push_str(" |\n");
        let _ = writeln!(
            out,
            "| Accepted at | sequence {} |",
            header.acceptance_sequence
        );
        if self.visible(record) {
            let _ = writeln!(
                out,
                "| Recorded | {} by {} |",
                header.recorded_at,
                table_code(&header.recorded_by.to_string())
            );
            let effective = self.classifier.effective(record);
            let _ = writeln!(
                out,
                "| Classification | {} (effective) |",
                level_word(effective.level)
            );
            if inherited_trust::is_authored(kind) {
                let trust =
                    Resolver::new(self.case.state(), self.case.sessions()).inherited(record);
                let _ = writeln!(
                    out,
                    "| Inherited trust | {} (declared inputs {}, session reads {}, revisions without a session {}) |",
                    inline_code(trust.level.as_str()),
                    trust.inputs.len(),
                    trust.session_reads_total(),
                    trust.undeclared_sessions()
                );
                let _ = writeln!(
                    out,
                    "| Trust limits | {} |",
                    inline_text(inherited_trust::LIMITS, inherited_trust::LIMITS.len())
                );
            }
        }
        let _ = writeln!(out, "{}", snapshot_row(head));
        Ok(())
    }

    /// The fixed body sections after [`Self::open_note`].
    pub fn sections(&self, out: &mut String, record: &Record) -> Result<(), RenderError> {
        self.summary_section(out, record)?;
        self.reference_sections(out, record)
    }

    /// `## Summary`: the first fixed section. Per-type sections follow it.
    pub fn summary_section(&self, out: &mut String, record: &Record) -> Result<(), RenderError> {
        out.push_str("\n## Summary\n\n");
        if self.visible(record) {
            self.summary(out, record)?;
        } else {
            out.push_str("Withheld.\n");
        }
        Ok(())
    }

    /// The fixed sections after the per-type ones: typed links, evidence
    /// selectors, and next action or blocker.
    pub fn reference_sections(&self, out: &mut String, record: &Record) -> Result<(), RenderError> {
        let visible = self.visible(record);
        out.push_str("\n## Typed links\n\n");
        if self.may_show(record, Field::Lineage) {
            self.typed_links(out, record)?;
        } else {
            out.push_str("Withheld.\n");
        }
        out.push_str("\n## Evidence selectors\n\n");
        if self.may_show(record, Field::Content) {
            selectors(out, record);
        } else {
            out.push_str("Withheld.\n");
        }
        out.push_str("\n## Next action or blocker\n\n");
        if visible {
            self.next_action(out, record)?;
        } else {
            out.push_str("Withheld.\n");
        }
        Ok(())
    }

    fn summary(&self, out: &mut String, record: &Record) -> Result<(), RenderError> {
        let body = &record.body;
        let claim = first_text(body, title_fields(record.header.id.kind()))
            .map(|text| inline_text(text, SUMMARY_CHARS))
            .or_else(|| self.derived_title(record))
            .unwrap_or_else(|| "not recorded".to_owned());
        let applicability = first_text(body, APPLICABILITY_FIELDS).map_or_else(
            || "not recorded".to_owned(),
            |text| inline_text(text, SUMMARY_CHARS),
        );
        let _ = writeln!(out, "- Claim: {claim}");
        let _ = writeln!(out, "- Applicability: {applicability}");
        let Some(effective) = self.effective(record) else {
            out.push_str("- Effective state: unknown at this snapshot\n");
            return Ok(());
        };
        let _ = writeln!(
            out,
            "- Effective state: {} (recorded lifecycle {})",
            inline_code(effective.freshness.as_str()),
            inline_code(effective.lifecycle.as_deref().unwrap_or("recorded"))
        );
        if effective.reasons.is_empty() {
            out.push_str("- Caveat: none recorded\n");
        }
        for reason in &effective.reasons {
            let _ = writeln!(out, "- Caveat: {}", self.reason_text(reason)?);
        }
        Ok(())
    }

    /// One freshness reason: severity, trigger, cause and the first step of
    /// the dependency path that reaches it.
    pub(crate) fn reason_text(&self, reason: &FreshnessReason) -> Result<String, RenderError> {
        let mut text = format!(
            "{} because of {} at {} revision {}",
            inline_code(reason.freshness.as_str()),
            inline_code(&wire_word(&reason.trigger)),
            self.link(reason.cause.id)?,
            reason.cause.revision
        );
        if let Some(step) = reason.path.first() {
            let _ = write!(
                text,
                ", reached through {} ({} step{})",
                inline_code(&step.field),
                reason.path.len(),
                if reason.path.len() == 1 { "" } else { "s" }
            );
        }
        Ok(text)
    }

    fn typed_links(&self, out: &mut String, record: &Record) -> Result<(), RenderError> {
        let state = self.case.state();
        out.push_str("### Relies on\n\n");
        match dependency_edges(record) {
            Err(_) => out.push_str("The stored references of this record cannot be read.\n"),
            Ok(edges) if edges.is_empty() => out.push_str("No recorded references.\n"),
            Ok(edges) => {
                for edge in edges {
                    let _ = write!(
                        out,
                        "- {} through {}, citing revision {}",
                        self.link(edge.target.id)?,
                        inline_code(edge.field),
                        edge.target.revision
                    );
                    if let Some(current) = state.current(edge.target.id)
                        && current.header.revision.0 != edge.target.revision
                    {
                        let _ = write!(out, " (current revision {})", current.header.revision.0);
                    }
                    out.push_str(match edge.propagation {
                        Propagation::Inherit => "; inherits its freshness\n",
                        Propagation::ChangeOnly => "; affected by changes to it only\n",
                    });
                }
            }
        }
        let named = mentions(record);
        if !named.is_empty() {
            out.push_str("\n### Also names\n\n");
            for mention in &named {
                let _ = write!(
                    out,
                    "- {} in {}",
                    self.link(mention.target)?,
                    inline_code(&mention.field)
                );
                if let Some(revision) = mention.revision {
                    let _ = write!(out, ", revision {revision}");
                }
                out.push_str("; no freshness dependency\n");
            }
        }
        out.push_str("\n### Cited by\n\n");
        let mut any = false;
        for citation in self.cited_by.get(&record.header.id).into_iter().flatten() {
            // A withheld record's references are its lineage: omit it entirely.
            let Some(citing) = state.current(citation.by) else {
                continue;
            };
            if !self.may_show(citing, Field::Lineage) {
                continue;
            }
            any = true;
            let _ = write!(
                out,
                "- {} through {}, citing revision {}",
                self.link(citation.by)?,
                inline_code(citation.field),
                citation.cites.revision
            );
            if citation.cites.revision != record.header.revision.0 {
                let _ = write!(out, " (this is revision {})", record.header.revision.0);
            }
            out.push('\n');
        }
        for mention in self
            .mentioned_by
            .get(&record.header.id)
            .into_iter()
            .flatten()
        {
            let Some(citing) = state.current(mention.by) else {
                continue;
            };
            if !self.may_show(citing, Field::Lineage) {
                continue;
            }
            any = true;
            let _ = write!(
                out,
                "- {} names it in {}",
                self.link(mention.by)?,
                inline_code(&mention.field)
            );
            if let Some(revision) = mention.revision {
                let _ = write!(out, ", revision {revision}");
            }
            out.push('\n');
        }
        if !any {
            out.push_str("No recorded citations.\n");
        }
        Ok(())
    }

    fn next_action(&self, out: &mut String, record: &Record) -> Result<(), RenderError> {
        let mut any = false;
        match &self.gaps {
            None => {
                any = true;
                out.push_str("- The gap inventory is unavailable at this snapshot.\n");
            }
            Some(gaps) => {
                for gap in gaps.get(&record.header.id).into_iter().flatten() {
                    any = true;
                    if self.gap_withheld(&gap.gap_id) {
                        let _ = writeln!(
                            out,
                            "- Gap {}: details withheld by the view policy; the rule read a \
                             withheld record. Rule {}.",
                            inline_code(&wire_word(&gap.status)),
                            inline_code(&gap.rule_id)
                        );
                        continue;
                    }
                    let _ = write!(
                        out,
                        "- Gap {}: {}",
                        inline_code(&wire_word(&gap.status)),
                        inline_text(&gap.reason, SUMMARY_CHARS)
                    );
                    if let Some(operation) = &gap.suggested_operation {
                        let _ = write!(out, " Suggested operation: {}.", inline_code(operation));
                    }
                    let _ = writeln!(out, " Rule {}.", inline_code(&gap.rule_id));
                }
            }
        }
        if let Some(effective) = self.effective(record)
            && !effective.reasons.is_empty()
        {
            any = true;
            let _ = writeln!(
                out,
                "- Blocker: the effective state is {}; review the caveats above before relying on this record.",
                inline_code(effective.freshness.as_str())
            );
        }
        if !any {
            out.push_str("No open gap or reviewer blocker names this record at this snapshot.\n");
        }
        Ok(())
    }
}

/// The basis-table row naming the snapshot a note was rendered at, without
/// its line break. [`crate::incremental`] restamps exactly this row.
pub(crate) fn snapshot_row(head: &Snapshot) -> String {
    format!(
        "| Snapshot | sequence {}, head {} |",
        head.sequence,
        table_code(head.head_hash.as_str())
    )
}

/// Whether every record a rule read may be shown in full to the audience.
/// A reference to a revision this snapshot does not hold reads nothing.
fn reads_only_visible<'r>(
    classifier: &Classifier<'_>,
    audience: &AudiencePolicy,
    mut read: impl Iterator<Item = &'r RevisionRef>,
) -> bool {
    let state = classifier.state();
    read.all(|reference| {
        state
            .revision(*reference)
            .or_else(|| state.current(reference.id))
            .is_none_or(|record| classifier.may_show(record, Field::Content, audience))
    })
}

/// Every accepted evidence selector in a record body, by field path, in a
/// stable order.
fn find_selectors(
    value: &Value,
    path: &mut Vec<String>,
    found: &mut Vec<(String, EvidenceSelector)>,
) {
    match value {
        Value::Object(map) => {
            if map.get("schema_version").and_then(Value::as_str) == Some("inv.selector.v1")
                && map.contains_key("artifact_digest")
                && let Ok(selector) = serde_json::from_value::<EvidenceSelector>(value.clone())
            {
                found.push((path.join("."), selector));
                return;
            }
            for (key, child) in map {
                path.push(key.clone());
                find_selectors(child, path, found);
                path.pop();
            }
        }
        Value::Array(items) => {
            for (index, child) in items.iter().enumerate() {
                path.push(index.to_string());
                find_selectors(child, path, found);
                path.pop();
            }
        }
        _ => {}
    }
}

/// Block anchor for an excerpt: derived from the exact artifact digest and
/// selector, so it is stable across renders, revisions and note layouts and
/// never depends on rendered line numbers.
pub fn excerpt_anchor(selector: &EvidenceSelector) -> String {
    let exact = serde_json::to_string(&selector.selector).unwrap_or_default();
    let digest = hash_bytes(
        format!(
            "inv.excerpt-anchor.v1\n{}\n{exact}",
            selector.artifact_digest.as_str()
        )
        .as_bytes(),
    );
    let hex = digest.as_str().trim_start_matches("sha256:");
    format!("inv-sel-{}", &hex[..hex.len().min(16)])
}

/// One accepted evidence selector of a record with its block anchor in the
/// record's note.
pub(crate) struct AnchoredSelector {
    /// Dotted body field that holds the selector.
    pub field: String,
    pub selector: EvidenceSelector,
    /// [`excerpt_anchor`], suffixed when one note holds the same selector twice.
    pub anchor: String,
}

/// Every evidence selector of a record body with the block anchor its note
/// gives it, in note order.
pub(crate) fn anchored_selectors(record: &Record) -> Vec<AnchoredSelector> {
    let mut found = Vec::new();
    find_selectors(&record.body, &mut Vec::new(), &mut found);
    let mut seen: BTreeMap<String, usize> = BTreeMap::new();
    found
        .into_iter()
        .map(|(field, selector)| {
            let mut anchor = excerpt_anchor(&selector);
            let count = seen.entry(anchor.clone()).or_default();
            *count += 1;
            if *count > 1 {
                anchor = format!("{anchor}-{count}");
            }
            AnchoredSelector {
                field,
                selector,
                anchor,
            }
        })
        .collect()
}

fn selectors(out: &mut String, record: &Record) {
    let found = anchored_selectors(record);
    if found.is_empty() {
        out.push_str("This record cites no evidence selector.\n");
        return;
    }
    out.push_str(
        "Selectors identify the exact retained bytes; rendered line numbers are not source authority.\n\n",
    );
    for AnchoredSelector {
        field,
        selector,
        anchor,
    } in found
    {
        let exact = serde_json::to_string(&selector.selector).unwrap_or_default();
        let _ = writeln!(
            out,
            "- {}: artifact {}, {} selector, validation {}: {} ^{anchor}",
            inline_code(&field),
            inline_code(selector.artifact_digest.as_str()),
            inline_code(&wire_word(&selector.selector)),
            inline_code(&wire_word(&selector.validation)),
            inline_code(&exact),
        );
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn excerpt_anchors_follow_digest_and_selector_only() {
        let selector = |digest: char, exact: &str| -> EvidenceSelector {
            serde_json::from_value(serde_json::json!({
                "schema_version":"inv.selector.v1",
                "artifact_digest":format!("sha256:{}", digest.to_string().repeat(64)),
                "selector":{"type":"text_quote","exact":exact,"prefix":null,"suffix":null},
                "validation":"verified"
            }))
            .unwrap()
        };
        let base = excerpt_anchor(&selector('a', "timeout"));
        assert_eq!(base, excerpt_anchor(&selector('a', "timeout")));
        assert_ne!(base, excerpt_anchor(&selector('b', "timeout")));
        assert_ne!(base, excerpt_anchor(&selector('a', "timeouts")));
        let mut unverified = selector('a', "timeout");
        unverified.validation = investigation_core::evidence::SelectorValidation::Unverified;
        assert_eq!(base, excerpt_anchor(&unverified));
        assert!(base.starts_with("inv-sel-") && base.len() == 24);
        assert!(
            base.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'-'),
            "Obsidian block IDs allow letters, digits and dashes only"
        );
    }
}
