//! `vault unrelease`: return paths released with `vault reconcile
//! --disposition release-path` to the projection
//! ([`investigation_render::reconcile::unrelease_vault`]).
//!
//! A path is returned only when nothing is at it any more; the person's file
//! is never moved, replaced, removed or adopted to make room. `--dry-run`
//! checks the request and writes nothing. Canonical state is not touched.

use std::fmt::Write as _;

use investigation_core::wire::{ErrorCode, Failure};
use investigation_render::{
    VaultRenderer,
    reconcile::{MAX_PATHS, Returned, UnreleaseReport, preview_unrelease, unrelease_vault},
    working_policy,
};
use investigation_store::{Store, Workspace};
use serde_json::{Value, json};

use crate::{
    Output, display_argv,
    vault::{argv, drift_json},
};

pub(crate) const AFTER_HELP: &str = "\
Return paths released with vault reconcile --disposition release-path to the
projection. A released file is yours, and the renderer never moves, replaces,
removes or takes it over, so a path is returned only when nothing is at it any
more: move your file out of the projection (into Notes/, for example) or delete
it first. The record is then projected at the path again, generated links point
back to it, and the note at the relocated path (<name>-2.md) is removed while
it holds its generated bytes; an edited one stays, and vault conflicts lists
it. Links in your own notes to the relocated path stop resolving. Releasing
the path again with release-path undoes this. vault status lists the released
paths. --dry-run checks the request and writes nothing.
Examples:
  investigation --workspace ./casework vault status --format json
  investigation --workspace ./casework vault unrelease Cases/<case-id>/Questions/<id>.md --dry-run --format json
Next: investigation --workspace ./casework vault status --format json";

#[derive(clap::Args)]
pub(crate) struct UnreleaseArgs {
    /// Released vault paths, as vault status lists them; an explicit list.
    #[arg(value_name = "PATH", required = true, num_args = 1..)]
    paths: Vec<String>,
    /// Check the request and print what would happen; change nothing.
    #[arg(long)]
    dry_run: bool,
}

pub(crate) fn run(store: &mut Store, args: &UnreleaseArgs) -> Result<Output, Failure> {
    if args.paths.len() > MAX_PATHS {
        return Err(Failure::new(
            ErrorCode::InvalidInput,
            format!("List at most {MAX_PATHS} paths in one request."),
        )
        .at("PATH"));
    }
    // Every refusal names the listing of released paths as its repair.
    let refused = |workspace: &Workspace, error: investigation_render::RenderError| {
        let failure = error.to_failure();
        if failure.error.repair.is_some() {
            failure
        } else {
            failure.with_argv(argv(workspace, &["vault", "status"]))
        }
    };
    if args.dry_run {
        let returned = preview_unrelease(store.workspace(), &args.paths)
            .map_err(|error| refused(store.workspace(), error))?;
        return Ok(output(store.workspace(), args, &returned, None));
    }
    let policy = working_policy(store.workspace());
    let report = unrelease_vault(store, &VaultRenderer, &policy, &args.paths, &mut |_| {})
        .map_err(|error| refused(store.workspace(), error))?;
    Ok(output(
        store.workspace(),
        args,
        &report.returned,
        Some(&report),
    ))
}

fn step_json(step: &Returned) -> Value {
    json!({
        "path":step.path.as_str(),
        "relocated_from":step.relocated_from.as_str(),
        "projects":step.projects,
    })
}

fn output(
    workspace: &Workspace,
    args: &UnreleaseArgs,
    returned: &[Returned],
    report: Option<&UnreleaseReport>,
) -> Output {
    let dry_run = report.is_none();
    let remaining: Vec<Value> = report
        .map(|report| report.remaining().into_iter().map(drift_json).collect())
        .unwrap_or_default();
    let render = report.map_or(Value::Null, |report| {
        let publish = &report.render.publish;
        json!({
            "generation":publish.generation.id(),
            "written":publish.written(),
            "unchanged":publish.unchanged(),
            "removed":publish.removed(),
            "refused":publish.refused(),
            "drifted":report.render.drift.len(),
        })
    });
    let next_tail: Vec<&str> = if dry_run {
        let mut tail = vec!["vault", "unrelease"];
        tail.extend(args.paths.iter().map(String::as_str));
        tail
    } else if remaining.is_empty() {
        vec!["vault", "status"]
    } else {
        vec!["vault", "conflicts"]
    };
    let next_argv = argv(workspace, &next_tail);
    let value = json!({
        "dry_run":dry_run,
        "paths":returned.iter().map(step_json).collect::<Vec<_>>(),
        "render":render,
        "remaining_drift":remaining,
        "clear":!dry_run && remaining.is_empty(),
        "next":[{"kind":if dry_run { "local_write" } else { "local_read" },"argv":next_argv}],
    });
    let mut text = format!(
        "{}  {} path(s)",
        if dry_run {
            "would unrelease"
        } else {
            "unreleased"
        },
        returned.len()
    );
    for step in returned {
        let _ = write!(
            text,
            "\n{}  record {} here again; {} retired",
            step.path,
            if dry_run {
                "would be projected"
            } else {
                "projected"
            },
            step.relocated_from
        );
    }
    if !remaining.is_empty() {
        let _ = write!(text, "\nstill drifted: {}", remaining.len());
    }
    let _ = write!(text, "\nNext: {}", display_argv(&next_argv));
    Output::success(
        if dry_run {
            "vault_unrelease_preview"
        } else {
            "vault_unreleased"
        },
        value,
        text,
    )
}
