//! Embed the checked-in scenario workspaces that `demo` replays.
//!
//! `fixtures/vault-goldens/<scenario>/workspace/` holds each scenario's
//! committed journal and retained blobs, built by the scenario proofs through
//! `scripts/vault-goldens.py --rebuild-workspaces`. This script lists the
//! files `demo` needs (the config, the workspace marker, case genesis files,
//! events and blobs; never locks) and includes their bytes, so the binary
//! replays the same fixtures the golden vaults are rendered from without a
//! second copy.
//!
//! It also lists the documents that the docs-versus-binary tests check
//! (REL.02) and includes their text, for tests only. A test then checks the
//! documents as they were when its binary was built: a worktree rewritten
//! while tests run (a sync of the workspace, for example) cannot pair new
//! documents with an older binary (bn-3dy5).

use std::{
    env, fs,
    path::{Path, PathBuf},
};

const SCENARIOS: [&str; 4] = ["scenario-a", "scenario-b", "scenario-c", "scenario-d"];

/// Documents outside `docs/` and `methods/` that the REL.02 checks read.
const DOCUMENTS: [&str; 8] = [
    "README.md",
    "AGENTS.md",
    "obsidian/README.md",
    "schemas/README.md",
    "scripts/README.md",
    "examples/README.md",
    "examples/python-producer/README.md",
    "examples/rust-producer/README.md",
];

/// The `.md` and `.toml` files under `dir`, as paths relative to `root`.
fn documents(root: &Path, dir: &Path, out: &mut Vec<String>) {
    let mut entries: Vec<_> = fs::read_dir(dir)
        .unwrap_or_else(|error| panic!("read {}: {error}", dir.display()))
        .map(|entry| entry.expect("directory entry").path())
        .collect();
    entries.sort();
    for path in entries {
        if path.is_dir() {
            documents(root, &path, out);
        } else if path
            .extension()
            .is_some_and(|extension| extension == "md" || extension == "toml")
        {
            let relative = path.strip_prefix(root).expect("under the root");
            let relative = relative.to_str().expect("UTF-8 document path");
            out.push(relative.replace('\\', "/"));
        }
    }
}

/// `documents.rs`: every document the REL.02 checks read, as (path relative
/// to the repository, text), sorted by path.
fn document_table(repository: &Path) -> String {
    let mut list: Vec<String> = DOCUMENTS.iter().map(|file| (*file).to_owned()).collect();
    for file in DOCUMENTS {
        println!("cargo:rerun-if-changed={}", repository.join(file).display());
    }
    for dir in ["docs", "methods"] {
        println!("cargo:rerun-if-changed={}", repository.join(dir).display());
        documents(repository, &repository.join(dir), &mut list);
    }
    list.sort();
    let mut generated = String::from(
        "// Generated by build.rs: the documents of the REL.02 checks.\n\
         pub(crate) static DOCUMENTS: &[(&str, &str)] = &[\n",
    );
    for relative in list {
        let path = fs::canonicalize(repository.join(&relative)).expect("document path");
        generated.push_str(&format!(
            "    ({relative:?}, include_str!({:?})),\n",
            path.to_str().expect("UTF-8 document path")
        ));
    }
    generated.push_str("];\n");
    generated
}

fn files(root: &Path, dir: &Path, out: &mut Vec<(String, PathBuf)>) {
    let mut entries: Vec<_> = fs::read_dir(dir)
        .unwrap_or_else(|error| panic!("read {}: {error}", dir.display()))
        .map(|entry| entry.expect("directory entry").path())
        .collect();
    entries.sort();
    for path in entries {
        if path.is_dir() {
            files(root, &path, out);
            continue;
        }
        let relative = path
            .strip_prefix(root)
            .expect("under the root")
            .to_str()
            .expect("UTF-8 fixture path")
            .replace('\\', "/");
        let wanted = relative == "investigation.toml"
            || relative == "state/workspace.json"
            || relative.starts_with("state/blobs/")
            || (relative.starts_with("state/cases/")
                && (relative.ends_with("/genesis.json") || relative.contains("/events/")));
        if wanted {
            out.push((relative, path));
        }
    }
}

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("cargo sets it"));
    let goldens = manifest.join("../../fixtures/vault-goldens");
    let mut generated = String::from("// Generated by build.rs from fixtures/vault-goldens.\n");
    for scenario in SCENARIOS {
        let root = goldens.join(scenario).join("workspace");
        println!("cargo:rerun-if-changed={}", root.display());
        let mut list = Vec::new();
        files(&root, &root, &mut list);
        generated.push_str(&format!(
            "pub(crate) static {}: &[(&str, &[u8])] = &[\n",
            scenario.replace('-', "_").to_uppercase()
        ));
        for (relative, path) in list {
            let path = fs::canonicalize(&path).expect("fixture path");
            generated.push_str(&format!(
                "    ({relative:?}, include_bytes!({:?})),\n",
                path.to_str().expect("UTF-8 fixture path")
            ));
        }
        generated.push_str("];\n");
    }
    println!("cargo:rerun-if-changed=build.rs");
    let out = PathBuf::from(env::var("OUT_DIR").expect("cargo sets it"));
    fs::write(out.join("demo_fixtures.rs"), generated).expect("write the fixture table");
    let documents = document_table(&manifest.join("../.."));
    fs::write(out.join("documents.rs"), documents).expect("write the document table");
}
